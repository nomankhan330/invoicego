<?php

namespace App\Services;

use App\Models\SystemSetting;
use Illuminate\Http\Response;
use Illuminate\Support\Facades\Storage;

class BrandLogoService
{
    public const KEY_LIGHT_B64 = 'brand_logo_light_b64';
    public const KEY_LIGHT_MIME = 'brand_logo_light_mime';
    public const KEY_DARK_B64 = 'brand_logo_dark_b64';
    public const KEY_DARK_MIME = 'brand_logo_dark_mime';
    public const KEY_VERSION = 'brand_logo_version';
    public const KEY_TRANSPARENT = 'brand_logo_transparent';
    public const KEY_AUTO_DARK = 'brand_logo_auto_dark';

    public static function version(): string
    {
        return (string) (SystemSetting::get(self::KEY_VERSION, '2') ?: '2');
    }

    public static function lightUrl(): string
    {
        return url('/brand/logo/light') . '?v=' . urlencode(self::version());
    }

    public static function darkUrl(): string
    {
        return url('/brand/logo/dark') . '?v=' . urlencode(self::version());
    }

    public static function hasCustomLogo(): bool
    {
        return !empty(SystemSetting::get(self::KEY_LIGHT_B64))
            || !empty(SystemSetting::get(self::KEY_DARK_B64));
    }

    public static function isTransparentEnabled(): bool
    {
        return (bool) SystemSetting::get(self::KEY_TRANSPARENT, true);
    }

    public static function isAutoDarkEnabled(): bool
    {
        return (bool) SystemSetting::get(self::KEY_AUTO_DARK, true);
    }

    /**
     * Serve the active Light or Dark brand logo from SystemSettings (DB-backed for Vercel + Local)
     * with seamless fallback to the default static PNG in public/images.
     */
    public function streamResponse(string $variant): Response
    {
        $variant = $variant === 'dark' ? 'dark' : 'light';
        $b64Key = $variant === 'dark' ? self::KEY_DARK_B64 : self::KEY_LIGHT_B64;
        $mimeKey = $variant === 'dark' ? self::KEY_DARK_MIME : self::KEY_LIGHT_MIME;

        $b64 = SystemSetting::get($b64Key);
        if (!empty($b64)) {
            $binary = base64_decode((string) $b64, true);
            if ($binary !== false && strlen($binary) > 0) {
                $mime = (string) (SystemSetting::get($mimeKey, 'image/png') ?: 'image/png');
                return response($binary, 200, [
                    'Content-Type' => $mime,
                    'Cache-Control' => 'public, max-age=31536000, immutable',
                ]);
            }
        }

        $fallbackFile = $variant === 'dark'
            ? public_path('images/invoicego-logo-dark.png')
            : public_path('images/invoicego-logo.png');

        if (!is_file($fallbackFile)) {
            abort(404);
        }

        return response((string) file_get_contents($fallbackFile), 200, [
            'Content-Type' => 'image/png',
            'Cache-Control' => 'public, max-age=86400',
        ]);
    }

    /**
     * Process and persist newly uploaded Light and/or Dark brand logos.
     * Supports automatic smooth white-background removal (transparent PNG) OR keeping original background,
     * plus automatic Dark Mode variant generation.
     */
    public function saveUploadedLogos(
        ?string $lightFilePath,
        ?string $darkFilePath,
        bool $makeTransparent = true,
        bool $autoGenerateDark = true
    ): void {
        SystemSetting::set(self::KEY_TRANSPARENT, $makeTransparent ? '1' : '0', 'general', 'boolean');
        SystemSetting::set(self::KEY_AUTO_DARK, $autoGenerateDark ? '1' : '0', 'general', 'boolean');

        $lightBytes = null;
        $lightMime = 'image/png';
        $darkBytes = null;
        $darkMime = 'image/png';

        if (!empty($lightFilePath) && is_file($lightFilePath)) {
            $processed = $this->processImageFile($lightFilePath, $makeTransparent, $autoGenerateDark);
            $lightBytes = $processed['light_bytes'];
            $lightMime = $processed['light_mime'];

            if (empty($darkFilePath)) {
                $darkBytes = $autoGenerateDark ? $processed['dark_bytes'] : $lightBytes;
                $darkMime = $autoGenerateDark ? $processed['dark_mime'] : $lightMime;
            }
        }

        if (!empty($darkFilePath) && is_file($darkFilePath)) {
            $processedDark = $this->processImageFile($darkFilePath, $makeTransparent, false);
            $darkBytes = $processedDark['light_bytes'];
            $darkMime = $processedDark['light_mime'];
        }

        if ($lightBytes !== null) {
            SystemSetting::set(self::KEY_LIGHT_B64, base64_encode($lightBytes), 'general', 'string');
            SystemSetting::set(self::KEY_LIGHT_MIME, $lightMime, 'general', 'string');
            $this->syncStaticFileIfWritable(public_path('images/invoicego-logo.png'), $lightBytes, $lightMime);
        }

        if ($darkBytes !== null) {
            SystemSetting::set(self::KEY_DARK_B64, base64_encode($darkBytes), 'general', 'string');
            SystemSetting::set(self::KEY_DARK_MIME, $darkMime, 'general', 'string');
            $this->syncStaticFileIfWritable(public_path('images/invoicego-logo-dark.png'), $darkBytes, $darkMime);
        }

        SystemSetting::set(self::KEY_VERSION, (string) time(), 'general', 'string');
    }

    /**
     * Restore the built-in default InvoiceGO transparent Light & Dark logos.
     */
    public function resetToDefault(): void
    {
        SystemSetting::whereIn('key', [
            self::KEY_LIGHT_B64,
            self::KEY_LIGHT_MIME,
            self::KEY_DARK_B64,
            self::KEY_DARK_MIME,
        ])->delete();

        $defaultLight = public_path('images/invoicego-logo-default.png');
        $defaultDark = public_path('images/invoicego-logo-dark-default.png');

        if (is_file($defaultLight) && is_writable(dirname(public_path('images/invoicego-logo.png')))) {
            @copy($defaultLight, public_path('images/invoicego-logo.png'));
        }
        if (is_file($defaultDark) && is_writable(dirname(public_path('images/invoicego-logo-dark.png')))) {
            @copy($defaultDark, public_path('images/invoicego-logo-dark.png'));
        }

        SystemSetting::set(self::KEY_TRANSPARENT, '1', 'general', 'boolean');
        SystemSetting::set(self::KEY_AUTO_DARK, '1', 'general', 'boolean');
        SystemSetting::set(self::KEY_VERSION, (string) time(), 'general', 'string');
    }

    /**
     * Resolve a Filament FileUpload stored path (on local disk) to an absolute file path.
     */
    public static function resolveDiskPath(?string $storedPath): ?string
    {
        if (empty($storedPath)) {
            return null;
        }

        if (is_file($storedPath)) {
            return $storedPath;
        }

        foreach (['local', 'public'] as $disk) {
            if (Storage::disk($disk)->exists($storedPath)) {
                return Storage::disk($disk)->path($storedPath);
            }
        }

        return null;
    }

    /**
     * Process an uploaded logo file (PNG, JPG, WEBP, SVG) into optimized Light & Dark PNG bytes.
     *
     * @return array{light_bytes: string, light_mime: string, dark_bytes: string, dark_mime: string}
     */
    protected function processImageFile(string $filePath, bool $makeTransparent, bool $generateDark): array
    {
        $raw = (string) file_get_contents($filePath);
        $ext = strtolower(pathinfo($filePath, PATHINFO_EXTENSION));

        // SVG passthrough (already vector & transparent)
        if ($ext === 'svg' || str_contains(ltrim(substr($raw, 0, 200)), '<svg')) {
            return [
                'light_bytes' => $raw,
                'light_mime' => 'image/svg+xml',
                'dark_bytes' => $raw,
                'dark_mime' => 'image/svg+xml',
            ];
        }

        if (!extension_loaded('gd')) {
            $mime = mime_content_type($filePath) ?: 'image/png';
            return [
                'light_bytes' => $raw,
                'light_mime' => $mime,
                'dark_bytes' => $raw,
                'dark_mime' => $mime,
            ];
        }

        $src = @imagecreatefromstring($raw);
        if (!$src) {
            $mime = mime_content_type($filePath) ?: 'image/png';
            return [
                'light_bytes' => $raw,
                'light_mime' => $mime,
                'dark_bytes' => $raw,
                'dark_mime' => $mime,
            ];
        }

        $w = imagesx($src);
        $h = imagesy($src);

        // Downscale giant uploads (> 1400px wide) to keep DB storage & page load blazing fast
        if ($w > 1400) {
            $newW = 1400;
            $newH = max(1, (int) round($h * ($newW / $w)));
            $resized = imagecreatetruecolor($newW, $newH);
            imagealphablending($resized, false);
            imagesavealpha($resized, true);
            $trans = imagecolorallocatealpha($resized, 0, 0, 0, 127);
            imagefill($resized, 0, 0, $trans);
            imagecopyresampled($resized, $src, 0, 0, 0, 0, $newW, $newH, $w, $h);
            imagedestroy($src);
            $src = $resized;
            $w = $newW;
            $h = $newH;
        }

        // Check if source already contains meaningful transparency
        $hasTransparency = $this->imageHasTransparency($src, $w, $h);

        // Detect bounding box & dominant accent color (if white-bg removal is requested)
        $minX = $w; $minY = $h; $maxX = 0; $maxY = 0;
        for ($y = 0; $y < $h; $y++) {
            for ($x = 0; $x < $w; $x++) {
                $rgba = imagecolorat($src, $x, $y);
                $a = ($rgba >> 24) & 0x7F;
                $r = ($rgba >> 16) & 0xFF;
                $g = ($rgba >> 8) & 0xFF;
                $b = $rgba & 0xFF;

                $isEmpty = $hasTransparency
                    ? ($a >= 122)
                    : ($makeTransparent && $r > 245 && $g > 245 && $b > 245);

                if (!$isEmpty) {
                    if ($x < $minX) $minX = $x;
                    if ($y < $minY) $minY = $y;
                    if ($x > $maxX) $maxX = $x;
                    if ($y > $maxY) $maxY = $y;
                }
            }
        }

        // If bounding box is valid and we're trimming transparent/white margins
        if ($maxX >= $minX && $maxY >= $minY && ($makeTransparent || $hasTransparency)) {
            $padX = max(6, (int) round(($maxX - $minX + 1) * 0.015));
            $padY = max(6, (int) round(($maxY - $minY + 1) * 0.04));
            $cropX = max(0, $minX - $padX);
            $cropY = max(0, $minY - $padY);
            $cropW = min($w - $cropX, ($maxX - $minX + 1) + ($padX * 2));
            $cropH = min($h - $cropY, ($maxY - $minY + 1) + ($padY * 2));
        } else {
            $cropX = 0;
            $cropY = 0;
            $cropW = $w;
            $cropH = $h;
        }

        $lightImg = $this->createTransparentCanvas($cropW, $cropH);
        $darkImg = $generateDark ? $this->createTransparentCanvas($cropW, $cropH) : null;

        for ($y = 0; $y < $cropH; $y++) {
            for ($x = 0; $x < $cropW; $x++) {
                $rgba = imagecolorat($src, $cropX + $x, $cropY + $y);
                $a = ($rgba >> 24) & 0x7F;
                $r = ($rgba >> 16) & 0xFF;
                $g = ($rgba >> 8) & 0xFF;
                $b = $rgba & 0xFF;

                if ($hasTransparency) {
                    // Already transparent PNG: preserve exact pixels for light version
                    if ($a >= 125) {
                        continue;
                    }
                    $cLight = imagecolorallocatealpha($lightImg, $r, $g, $b, $a);
                    imagesetpixel($lightImg, $x, $y, $cLight);

                    if ($darkImg !== null) {
                        [$dr, $dg, $db] = $this->adaptPixelForDarkMode($r, $g, $b);
                        $cDark = imagecolorallocatealpha($darkImg, $dr, $dg, $db, $a);
                        imagesetpixel($darkImg, $x, $y, $cDark);
                    }
                } elseif ($makeTransparent) {
                    // Opaque white-background logo -> smooth anti-aliased transparent PNG
                    $maxC = max($r, $g, $b);
                    $minC = min($r, $g, $b);
                    $saturation = $maxC - $minC;

                    if ($minC >= 246 && $saturation < 10) {
                        continue; // 100% transparent
                    }

                    if ($saturation >= 14) {
                        // Colored brand pixel (e.g. Royal Blue, Green, Red, etc.): unblend from white
                        // alpha = (255 - minC) / 255
                        $alphaF = (255.0 - $minC) / 255.0;
                        $alphaF = max(0.0, min(1.0, $alphaF));
                        if ($alphaF < 0.04) continue;
                        $effA = $alphaF > 0.96 ? 1.0 : $alphaF;

                        // Recover true foreground color unblended from white
                        $fr = (int) max(0, min(255, round(($r - 255.0 * (1.0 - $effA)) / $effA)));
                        $fg = (int) max(0, min(255, round(($g - 255.0 * (1.0 - $effA)) / $effA)));
                        $fb = (int) max(0, min(255, round(($b - 255.0 * (1.0 - $effA)) / $effA)));

                        $gdAlpha = max(0, min(127, (int) round((1.0 - $effA) * 127)));
                        $cLight = imagecolorallocatealpha($lightImg, $fr, $fg, $fb, $gdAlpha);
                        imagesetpixel($lightImg, $x, $y, $cLight);

                        if ($darkImg !== null) {
                            [$dr, $dg, $db] = $this->adaptPixelForDarkMode($fr, $fg, $fb);
                            $cDark = imagecolorallocatealpha($darkImg, $dr, $dg, $db, $gdAlpha);
                            imagesetpixel($darkImg, $x, $y, $cDark);
                        }
                    } else {
                        // Neutral dark text/icon on white background
                        $lum = 0.299 * $r + 0.587 * $g + 0.114 * $b;
                        $alphaF = (255.0 - $lum) / 255.0;
                        $alphaF = max(0.0, min(1.0, $alphaF));
                        if ($alphaF < 0.04) continue;
                        if ($alphaF > 0.95) $alphaF = 1.0;

                        $gdAlpha = max(0, min(127, (int) round((1.0 - $alphaF) * 127)));
                        $cLight = imagecolorallocatealpha($lightImg, 10, 14, 23, $gdAlpha);
                        imagesetpixel($lightImg, $x, $y, $cLight);

                        if ($darkImg !== null) {
                            $cDark = imagecolorallocatealpha($darkImg, 255, 255, 255, $gdAlpha);
                            imagesetpixel($darkImg, $x, $y, $cDark);
                        }
                    }
                } else {
                    // Keep original background exactly as uploaded!
                    $cLight = imagecolorallocatealpha($lightImg, $r, $g, $b, $a);
                    imagesetpixel($lightImg, $x, $y, $cLight);

                    if ($darkImg !== null) {
                        $cDark = imagecolorallocatealpha($darkImg, $r, $g, $b, $a);
                        imagesetpixel($darkImg, $x, $y, $cDark);
                    }
                }
            }
        }

        imagedestroy($src);

        $lightBytes = $this->encodePng($lightImg);
        imagedestroy($lightImg);

        $darkBytes = $lightBytes;
        if ($darkImg !== null) {
            $darkBytes = $this->encodePng($darkImg);
            imagedestroy($darkImg);
        }

        return [
            'light_bytes' => $lightBytes,
            'light_mime' => 'image/png',
            'dark_bytes' => $darkBytes,
            'dark_mime' => 'image/png',
        ];
    }

    protected function adaptPixelForDarkMode(int $r, int $g, int $b): array
    {
        $maxC = max($r, $g, $b);
        $minC = min($r, $g, $b);
        $saturation = $maxC - $minC;
        $lum = 0.299 * $r + 0.587 * $g + 0.114 * $b;

        // Dark neutral grays/blacks -> crisp pure white for dark navy/slate backgrounds
        if ($saturation < 28 && $lum < 155) {
            return [255, 255, 255];
        }

        // Lift dark saturated brand colors slightly so they glow vividly on dark surfaces
        if ($lum < 150) {
            $boost = 55;
            return [
                min(255, $r + $boost),
                min(255, $g + $boost),
                min(255, $b + (int) round($boost * 0.5)),
            ];
        }

        return [$r, $g, $b];
    }

    protected function imageHasTransparency($img, int $w, int $h): bool
    {
        $stepX = max(1, (int) floor($w / 40));
        $stepY = max(1, (int) floor($h / 20));
        for ($y = 0; $y < $h; $y += $stepY) {
            for ($x = 0; $x < $w; $x += $stepX) {
                $a = (imagecolorat($img, $x, $y) >> 24) & 0x7F;
                if ($a > 20) {
                    return true;
                }
            }
        }
        return false;
    }

    protected function createTransparentCanvas(int $w, int $h)
    {
        $im = imagecreatetruecolor($w, $h);
        imagealphablending($im, false);
        imagesavealpha($im, true);
        $trans = imagecolorallocatealpha($im, 0, 0, 0, 127);
        imagefill($im, 0, 0, $trans);
        return $im;
    }

    protected function encodePng($img): string
    {
        ob_start();
        imagepng($img, null, 9);
        return (string) ob_get_clean();
    }

    protected function syncStaticFileIfWritable(string $targetPath, string $bytes, string $mime): void
    {
        if ($mime !== 'image/png') {
            return;
        }
        try {
            if (is_writable(dirname($targetPath))) {
                @file_put_contents($targetPath, $bytes);
            }
        } catch (\Throwable) {
            // Read-only serverless environment (e.g. Vercel) — DB serves /brand/logo/* directly
        }
    }
}
